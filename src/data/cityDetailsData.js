export function getCityDetails(slug) {
  if (!slug) return null;
  const key = slug.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return CITY_DETAILS[key] || Object.values(CITY_DETAILS).find(c => c.cityName.toLowerCase() === slug.toLowerCase() || c.slug === key);
}

